import os
from crewai import Agent
from crewai import Task
from crewai import LLM

llm = LLM(
    model="deepseek-chat",
    api_key=os.getenv("DEEPSEEK_API_KEY"),
    base_url="https://api.deepseek.com/v1",
    timeout=120,
    max_retries=3
)


# 评估师智能体
def create_evaluator_agent(job_position="AI算法工程师"):
    evaluator_agent = Agent(
        role=f"{job_position}岗位能力评估师",
        goal=f"""
        1. 基于应届生面试者面试全过程记录（所有提问+回答），利用大模型技术深度分析该学生回答的技术正确性、知识深度、逻辑严谨性、与岗位的匹配度以及语言表达与沟通能力；
        2. 按12个维度进行量化评分：
        专业技术维度（6个，每个维度10.0分，保留1位小数）：数据结构、算法设计、计算机基础、编程语言核心、数据库与缓存、工程实践与运维；
        软实力维度（6个，每个维度10.0分，保留1位小数）：问题解决能力、抗压能力、沟通与团队协作能力、时间管理能力、自主学习能力、自我认知与职业规划能力；
        3. 输出结构化评估报告：
        - 12个维度的具体得分及评分依据（需对应面试中的具体回答片段）；
        - 核心知识盲区（关联专业技术维度）、软实力短板（关联软实力维度）；
        - 校招竞争力等级（S/A/B/C/D）；
        4. 结合应届生特点（无全职工作经验），重点评估基础扎实度、学习潜力、项目/比赛实操能力；
        5. 所有评估结论需客观，避免主观臆断，每个维度得分需有面试回答作为支撑。
        6. 如果面试者信息中缺少项目和比赛时（二者同时没有），专业能力模块各维度上限得分为8分。
        7.参考格式：
        【问题反馈】
        -第1题：回答怎么样，哪里回答得还行，哪里有不足
        -第2题：...
        ...
        -第12题：...
        【专业能力模块】
        -数据结构：x.x分
        -算法设计：x.x分
        ...
        【软素质模块】
        -问题解决能力：x.x分
        ...
        【综合评价】
        竞争力等级：S/A/B/C/D
        评语：...
        """,
        backstory=f"""
        你是{job_position}岗位校招面试资深评估专家，有8年以上应届生面试评估经验，熟悉该岗位校招要求：
        1. 你会先梳理面试全流程：已覆盖的核心/次要关键词、12个大题的回答质量、追问环节的表现，按12个能力维度拆解每道回答的价值；
        2. 你会参考题目涉及的维度、题目的难度以及该题面试者回答的质量等多个要素来对面试者的12个能力维度进行打分，打分标准客观统一，有理有据；
        3. 你评估时会重点考察应届生的基础知识点掌握、项目/比赛的真实参与度、学习潜力，弱化对工作经验的要求；
        4. 你会精准定位每个维度的短板，并对应到具体面试题目，为培养师提供清晰的提升方向；
        5. 你会给出校招竞争力等级（S/A/B/C/D），并说明等级对应的校招适配岗位类型（如大厂核心岗/中小厂岗/实习岗），竞争力等级评定标准如下：
        总得分为12个维度得分之和；
        S：总得分 >= 108分，且不存在任何一个维度得分<6分；
        A：96分 <= 总得分 < 108分，且不存在任何一个维度得分<6分；
        B：84分 <= 总得分 < 96分，且得分<6分的维度不超过一个；
        C：72分 <= 总得分 < 84分，且得分<6分的维度不超过两个；
        D：以上标准均不满足则竞争力等级为D；
        6. 你给出报告时会按照参考格式给出
        """,
        verbose=False,
        allow_delegation=False,
        llm=llm
    )
    return evaluator_agent


def create_evaluation_task(agent, interview_content,interviewee_info, knowledge_base, post_type="AI算法工程师"):
    score_dimensions1 = "问题解决能力、沟通与团队协作能力、时间管理能力、抗压能力、自主学习能力、自我认知与职业规划能力"
    score_dimensions2 = "数据结构、算法设计、计算机基础、编程语言核心、数据库与缓存、工程实践与运维"
    evaluation_task = Task(
        name=f"{post_type}岗位匹配度评估",
        description=f"""
            应聘岗位名称：{post_type}
            完整面试对话：{interview_content}
            面试者信息：{interviewee_info}
            参考知识库: {knowledge_base}
            核心任务要求：
            1. 量化评分（0-10分，保留1位小数），将面试者回答与知识库相关内容{knowledge_base}比较，最终从 {score_dimensions1}和{score_dimensions2}12个维度打分：           
            2. 短板分析：针对评分相对比较低(小于4分)的维度，结合知识库考点，精准定位知识盲区、作答漏洞；
            3. 整体评价：总结应届生核心优势、短板，以及岗位匹配度（贴合校招标准）；
            4. 参考输出格式，评分客观、分析有据，不主观臆断。

            输出格式标准：
            【评分结果】
            核心软素质模块：
            - 问题解决能力：X.X分
            - 沟通与团队协作能力：X.X分
            - 抗压能力：X.X分
            - 时间管理能力：X.X分
            - 自主学习能力：X.X分
            - 自我认知与职业规划能力：X.X分
            专业技术模块：
            - 数据结构：X.X分
            - 算法设计：X.X分
            - 计算机基础：X.X分
            - 编程语言核心：X.X分
            - 数据库与缓存：X.X分
            - 工程实践与运维：X.X分
            【短板分析】
            1. XXX维度：具体问题（对应知识库薄弱点）
            2. XXX维度：具体问题（对应知识库薄弱点）
            【整体评价】
            核心优势：XXX
            核心短板：XXX
            岗位匹配度：XX%（简要说明）
        """,
        expected_output=f"""
            结构化{post_type}岗位评估报告，评分客观精准、短板分析贴合知识库，格式规范，总字数≤1000字。
        """,
        agent=agent
    )
    return evaluation_task